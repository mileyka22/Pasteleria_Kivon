USE defaultdb;
-- DROP TABLE IF EXISTS CLIENTE; --
CREATE TABLE CLIENTE
( id INT NOT NULL PRIMARY KEY AUTO_INCREMENT,
	Nombre VARCHAR(50) NOT NULL,
	Apellidos VARCHAR(100),
	CI VARCHAR(30) NOT NULL,
	Telefono VARCHAR(20),
	Direccion VARCHAR(250)
)ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

DROP TABLE IF EXISTS USUARIO;
CREATE TABLE USUARIO
( id INT NOT NULL PRIMARY KEY AUTO_INCREMENT,
	Username VARCHAR(50) NOT NULL,
	Permiso VARCHAR(100) NOT NULL,
	Password_hash VARCHAR(255) NOT NULL
)ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

DROP TABLE IF EXISTS PERSONAL;
CREATE TABLE PERSONAL
( id INT NOT NULL PRIMARY KEY AUTO_INCREMENT,
	Nombre VARCHAR(50) NOT NULL,
	Cargo VARCHAR(100) NOT NULL,
	Telefono VARCHAR(50),
	Salario DECIMAL(10,2) NOT NULL,
	id_usuario INT,
	
	CONSTRAINT FK_PERSONAL_USUARIO
	FOREIGN KEY(id_usuario) REFERENCES USUARIO(id)
	ON DELETE SET NULL ON UPDATE CASCADE
)ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

DROP TABLE IF EXISTS PRODUCTO;
CREATE TABLE PRODUCTO
( id INT NOT NULL PRIMARY KEY AUTO_INCREMENT,
	Nombre VARCHAR(80) NOT NULL,
	Precio DECIMAL(10,2) NOT NULL,
	Cantidad INT(100) NOT NULL,
	Ingrediente VARCHAR(255),
	Fecha_registro TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
	id_personal INT,
	
	CONSTRAINT FK_PRODUCTO_PERSONAL
	FOREIGN KEY(id_personal) REFERENCES PERSONAL(id)
	ON DELETE SET NULL ON UPDATE CASCADE
)ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

DROP TABLE IF EXISTS PEDIDO;
CREATE TABLE PEDIDO
( id INT NOT NULL PRIMARY KEY AUTO_INCREMENT,
	Estado VARCHAR(80) NOT NULL,
	Detalle VARCHAR(255),
	Fecha_entrega TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
	id_cliente INT,
	id_personal INT,
	
	CONSTRAINT FK_PEDIDO_CLIENTE
	FOREIGN KEY(id_cliente) REFERENCES CLIENTE(id)
	ON DELETE SET NULL ON UPDATE CASCADE,
	
	CONSTRAINT FK_PEDIDO_PERSONAL
	FOREIGN KEY(id_personal) REFERENCES PERSONAL(id)
	ON DELETE SET NULL ON UPDATE CASCADE
)ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

DROP TABLE IF EXISTS PRODUCTO_PEDIDO;
CREATE TABLE PRODUCTO_PEDIDO
( id INT NOT NULL PRIMARY KEY AUTO_INCREMENT,
	id_producto INT,
	id_pedido INT,
	Cantidad INT(100) NOT NULL,
	Precio_unitario DECIMAL(10,2) NOT NULL,
	
	CONSTRAINT FK_PRODUCTO_PEDIDO_PRODUCTO
	FOREIGN KEY(id_producto) REFERENCES PRODUCTO(id)
	ON DELETE SET NULL ON UPDATE CASCADE,
	
	CONSTRAINT FK_PRODUCTO_PEDIDO_PEDIDO
	FOREIGN KEY(id_pedido) REFERENCES PEDIDO(id)
	ON DELETE SET NULL ON UPDATE CASCADE
)ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

DROP TABLE IF EXISTS VENTA;
CREATE TABLE VENTA
( id INT NOT NULL PRIMARY KEY AUTO_INCREMENT,
	Fecha TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
	Total DECIMAL(10,2) NOT NULL,
	Metodo_de_pago VARCHAR(255) NOT NULL,
	id_personal INT,
	id_pedido INT,
	
	CONSTRAINT FK_VENTA_PEDIDO
	FOREIGN KEY(id_pedido) REFERENCES PEDIDO(id)
	ON DELETE SET NULL ON UPDATE CASCADE,
	
	CONSTRAINT FK_VENTA_PERSONAL
	FOREIGN KEY(id_personal) REFERENCES PERSONAL(id)
	ON DELETE SET NULL ON UPDATE CASCADE
)ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

